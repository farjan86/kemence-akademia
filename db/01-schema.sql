--  Tartalom: workshops (program) + idopontok (alkalmak) + bookings + settings
--  + biztonság (RLS) + szabad-helyek logika + túlfoglalás elleni védelem.
--
--  MODELL: egy PROGRAM (workshops) több IDŐPONTHOZ (idopontok) tartozhat;
--  egy FOGLALÁS (bookings) mindig egy konkrét IDŐPONTRA szól (idopont_id).
--  Az ár, kedvezményes ár, létszám és az „elmaradt" állapot IDŐPONTONKÉNT
