-- ---------------------------------------------------------------------
-- 4) SZABAD HELYEK — foglalt helyek számolása
--    security definer: anon is meg tudja hívni, de a foglalások
--    SORAIT nem látja — csak az összesített számot kapja meg.
-- ---------------------------------------------------------------------
create or replace function public.foglalt_helyek(p_workshop uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(letszam), 0)::int
  from public.bookings
  where workshop_id = p_workshop
    and statusz in ('jovahagyasra_var','jovahagyott');  -- ezek foglalnak helyet
$$;

-- Publikus programlista nézet: workshop-mezők + szabad helyek,
-- foglalási sorok kiszivárgása nélkül.
drop view if exists public.programok;
create view public.programok as
select
  w.id, w.cim, w.leiras, w.ar, w.kedvezmenyes_ar, w.idopont,
  w.varhato_idotartam, w.foto_url, w.statusz, w.max_letszam, w.archivalt,
  greatest(coalesce(w.max_letszam,0) - public.foglalt_helyek(w.id), 0) as szabad_helyek
from public.workshops w;

-- ---------------------------------------------------------------------
-- 5) TÚLFOGLALÁS ELLENI VÉDELEM — trigger
--    Foglalás beszúrásakor/módosításakor ellenőrzi a szabad helyet.
-- ---------------------------------------------------------------------
create or replace function public.ellenoriz_szabad_hely()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_max     integer;
  v_statusz text;
  v_idopont timestamptz;
  v_foglalt integer;
begin
  -- Csak a helyet foglaló (aktív) státuszoknál ellenőrzünk: így lezárt foglalás
  -- (lemondott/elutasított) bármikor módosítható elmaradt/archivált programon is.
  if new.statusz in ('jovahagyasra_var','jovahagyott') then
    select max_letszam, statusz, idopont into v_max, v_statusz, v_idopont
    from public.workshops where id = new.workshop_id;

    if v_statusz is distinct from 'aktiv' then
      raise exception 'Erre a programra nem lehet foglalni (nem aktív).';
    end if;

    -- Publikus (anon) foglalás NEM mehet MÚLTBÉLI eseményre; a mai nap még OK.
    -- Az admin / seed (nem anon) rögzíthet historikus adatot (pl. lezajlott program).
    if tg_op = 'INSERT'
       and coalesce(auth.role(), '') = 'anon'
       and v_idopont is not null
       and (v_idopont at time zone 'Europe/Budapest')::date
           < (now()      at time zone 'Europe/Budapest')::date then
      raise exception 'Erre a programra már nem lehet foglalni (lezárult).';
    end if;

    select coalesce(sum(letszam),0) into v_foglalt
    from public.bookings
    where workshop_id = new.workshop_id
      and statusz in ('jovahagyasra_var','jovahagyott')
      and id <> new.id;                        -- saját magát ne számolja (update)

    if v_foglalt + new.letszam > coalesce(v_max,0) then
      raise exception 'Nincs elég szabad hely (% szabad).',
        greatest(coalesce(v_max,0) - v_foglalt, 0);
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_szabad_hely on public.bookings;
create trigger trg_szabad_hely
before insert or update on public.bookings
for each row execute function public.ellenoriz_szabad_hely();

-- ---------------------------------------------------------------------
-- 6) BIZTONSÁG (Row Level Security)
--    Alapelv: a publikus látogató olvashat programot és beküldhet
--    foglalást, de foglalási adatokat NEM lát. Mindent más csak a
--    bejelentkezett admin.
--    (Egyetlen admin fiók lesz, önregisztráció nincs → minden
--     bejelentkezett = admin. Később szűkíthető konkrét e-mailre.)
-- ---------------------------------------------------------------------
alter table public.workshops      enable row level security;
alter table public.bookings       enable row level security;
alter table public.settings       enable row level security;
alter table public.email_sablonok enable row level security;
alter table public.email_log      enable row level security;

-- --- workshops ---
drop policy if exists workshops_read on public.workshops;
create policy workshops_read on public.workshops
  for select using (true);                                   -- bárki olvashatja

drop policy if exists workshops_admin on public.workshops;
create policy workshops_admin on public.workshops
  for all to authenticated
  using (auth.uid() is not null) with check (auth.uid() is not null);

-- --- bookings ---
drop policy if exists bookings_public_insert on public.bookings;
create policy bookings_public_insert on public.bookings           -- bárki beküldhet,
  for insert to anon, authenticated
  with check (statusz = 'jovahagyasra_var');                       -- de csak "vár" státusszal

drop policy if exists bookings_admin_read on public.bookings;
create policy bookings_admin_read on public.bookings
  for select to authenticated using (auth.uid() is not null);

drop policy if exists bookings_admin_update on public.bookings;
create policy bookings_admin_update on public.bookings
  for update to authenticated
  using (auth.uid() is not null) with check (auth.uid() is not null);

drop policy if exists bookings_admin_delete on public.bookings;
create policy bookings_admin_delete on public.bookings
  for delete to authenticated using (auth.uid() is not null);

-- --- settings ---
drop policy if exists settings_read on public.settings;
create policy settings_read on public.settings
  for select using (true);                                   -- a feladó cím olvasható

drop policy if exists settings_admin on public.settings;
create policy settings_admin on public.settings
  for all to authenticated
  using (auth.uid() is not null) with check (auth.uid() is not null);

-- --- email_sablonok (csak admin; a publikus nem látja) ---
drop policy if exists email_sablonok_admin on public.email_sablonok;
create policy email_sablonok_admin on public.email_sablonok
  for all to authenticated
  using (auth.uid() is not null) with check (auth.uid() is not null);

-- --- email_log (csak admin olvashatja; írás service-role-lal) ---
drop policy if exists email_log_read on public.email_log;
create policy email_log_read on public.email_log
  for select to authenticated using (auth.uid() is not null);

