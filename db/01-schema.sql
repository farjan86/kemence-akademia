-- ---------------------------------------------------------------------
-- 1) PROGRAMOK (workshops) — a program KÖZÖS adatai (minden időpontra)
-- ---------------------------------------------------------------------
create table if not exists public.workshops (
  id                 uuid primary key default gen_random_uuid(),
  cim                text        not null,
  rovid_leiras       text,                    -- rövid leírás a kártyára (kötelező az adminban)
  leiras             text,                    -- részletes leírás (OPCIONÁLIS), a „Részletek" ablakban
  eloado             text,                    -- előadó(k) neve; akár több név vesszővel („Szabó Zoltán, Nagy Andrea")
  varhato_idotartam  text,                    -- pl. "~4 óra"; opcionális
  foto_url           text,                    -- Storage-link; opcionális
  statusz            text not null default 'aktiv'
                       check (statusz in ('aktiv','hamarosan')),  -- 'hamarosan' = még nincs meghirdetett időpont
  archivalt          boolean not null default false,   -- ha true: nem jelenik meg a főoldalon
  foglalas_felfuggesztve boolean not null default false, -- átmeneti szünet: a publikus foglalás tiltva erre a programra
  created_at         timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2) IDŐPONTOK (idopontok) — egy program egy-egy meghirdetett alkalma
--    Ár/kedvezményes ár/létszám IDŐPONTONKÉNT; státusz: aktiv / elmaradt.
-- ---------------------------------------------------------------------
create table if not exists public.idopontok (
  id                 uuid primary key default gen_random_uuid(),
  workshop_id        uuid not null references public.workshops(id) on delete cascade,
  idopont            timestamptz not null,        -- dátum + idő
  ar                 integer not null,            -- Ft
  kedvezmenyes_ar    integer,                     -- opcionális akciós ár (< ar)
  max_letszam        integer not null,            -- férőhely erre az alkalomra
  max_foglalasok     integer,                     -- hány FOGLALÁS jöhet rá (null = korlátlan)
  min_letszam        integer,                     -- egy foglalás MIN. létszáma (null = nincs)
  statusz            text not null default 'aktiv'
                       check (statusz in ('aktiv','elmaradt')),   -- 'elmaradt' = ez az alkalom lemondva
  created_at         timestamptz not null default now(),

  -- akciós ár csak az alap ár alatt lehet
  constraint idopont_kedvezmeny_kisebb
    check (kedvezmenyes_ar is null or kedvezmenyes_ar < ar),
  constraint idopont_letszam_pozitiv
    check (max_letszam > 0),
  -- csoportos korlátok: pozitív értékek, és a minimum nem nagyobb a kapacitásnál
  constraint idopont_max_foglalasok_pozitiv
    check (max_foglalasok is null or max_foglalasok >= 1),
  constraint idopont_min_letszam_ervenyes
    check (min_letszam is null or (min_letszam >= 1 and min_letszam <= max_letszam))
);

-- ---------------------------------------------------------------------
-- 3) FOGLALÁSOK (bookings) — mindig egy KONKRÉT IDŐPONTRA (idopont_id)
-- ---------------------------------------------------------------------
create table if not exists public.bookings (
  id           uuid primary key default gen_random_uuid(),
  azonosito    bigint generated by default as identity (start with 1),     -- belső sorszám 1-től; megjelenítve: elotag + (azonosito + kezdo - 1)
  idopont_id   uuid not null references public.idopontok(id) on delete restrict,
  nev          text    not null,
  email        text    not null,
  telefon      text    not null,
  letszam      integer not null check (letszam > 0),
  megjegyzes   text,
  statusz      text not null default 'jovahagyasra_var'
                 check (statusz in ('jovahagyasra_var','jovahagyott','elutasitott','lemondott')),
  created_at   timestamptz not null default now()
);

create index if not exists workshops_archivalt_idx on public.workshops (archivalt);
create index if not exists idopontok_workshop_idx   on public.idopontok (workshop_id);
create index if not exists idopontok_idopont_idx     on public.idopontok (idopont);
create index if not exists bookings_idopont_idx      on public.bookings (idopont_id);
create index if not exists bookings_statusz_idx      on public.bookings (statusz);
create unique index if not exists bookings_azonosito_uniq on public.bookings (azonosito);

