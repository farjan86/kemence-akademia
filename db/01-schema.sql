-- ---------------------------------------------------------------------
-- 1) PROGRAMOK (workshops)
-- ---------------------------------------------------------------------
create table if not exists public.workshops (
  id                 uuid primary key default gen_random_uuid(),
  cim                text        not null,
  leiras             text        not null,
  ar                 integer,                 -- Ft; "aktív" programnál kötelező
  kedvezmenyes_ar    integer,                 -- opcionális akciós ár
  idopont            timestamptz,             -- dátum + idő; "aktív"-nál kötelező
  varhato_idotartam  text,                    -- pl. "~4 óra"; opcionális
  max_letszam        integer,                 -- "aktív"-nál kötelező
  foto_url           text,                    -- Storage-link; opcionális
  statusz            text not null default 'aktiv'
                       check (statusz in ('aktiv','hamarosan','elmaradt')),  -- elmaradt = a program lemondva
  archivalt          boolean not null default false,   -- ha true: nem jelenik meg a főoldalon
  created_at         timestamptz not null default now(),

  -- akciós ár csak az alap ár alatt lehet
  constraint kedvezmeny_kisebb
    check (kedvezmenyes_ar is null
           or (ar is not null and kedvezmenyes_ar < ar)),

  -- "aktív" (foglalható) programnál kötelező az ár, időpont, létszám;
  -- "hamarosan" státusznál csak a cím és a leírás kell
  constraint aktiv_kotelezo
    check (statusz <> 'aktiv'
           or (ar is not null and idopont is not null and max_letszam is not null)),

  constraint letszam_pozitiv
    check (max_letszam is null or max_letszam > 0)
);

-- ---------------------------------------------------------------------
-- 2) FOGLALÁSOK (bookings)
-- ---------------------------------------------------------------------
create table if not exists public.bookings (
  id           uuid primary key default gen_random_uuid(),
  azonosito    bigint generated by default as identity (start with 1),     -- belső sorszám 1-től; megjelenítve: elotag + (azonosito + kezdo - 1)
  workshop_id  uuid not null references public.workshops(id) on delete restrict,
  nev          text    not null,
  email        text    not null,
  telefon      text    not null,
  letszam      integer not null check (letszam > 0),
  megjegyzes   text,
  statusz      text not null default 'jovahagyasra_var'
                 check (statusz in ('jovahagyasra_var','jovahagyott','elutasitott','lemondott')),
  created_at   timestamptz not null default now()
);

create index if not exists workshops_archivalt_idx on public.workshops (archivalt);
create index if not exists bookings_workshop_idx on public.bookings (workshop_id);
create index if not exists bookings_statusz_idx   on public.bookings (statusz);
create unique index if not exists bookings_azonosito_uniq on public.bookings (azonosito);

